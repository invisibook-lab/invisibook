//! Measures what one ECVRF verification costs on CKB-VM.
//!
//! Deliberately free of ckb-std: the question is the cost of the cryptography,
//! and linking the syscall layer would need a RISC-V C toolchain without
//! changing the answer. Run it under `ckb-debugger` and read the cycle count.

#![no_std]
#![no_main]

use core::arch::asm;
use core::hint::black_box;
use core::panic::PanicInfo;

use ckb_vrf::verify;

/// A proof produced by the L2 chain's own prover.
const PUBKEY: [u8; 33] = [
    0x02, 0x84, 0xbf, 0x75, 0x62, 0x26, 0x2b, 0xbd, 0x69, 0x40, 0x08, 0x57, 0x48, 0xf3, 0xbe, 0x6a,
    0xfa, 0x52, 0xae, 0x31, 0x71, 0x55, 0x18, 0x1e, 0xce, 0x31, 0xb6, 0x63, 0x51, 0xcc, 0xff, 0xa4,
    0xb0,
];

const ALPHA: [u8; 53] = [
    0x69, 0x6e, 0x76, 0x69, 0x73, 0x69, 0x62, 0x6f, 0x6f, 0x6b, 0x2d, 0x76, 0x72, 0x66, 0x2d, 0x69,
    0x6e, 0x70, 0x75, 0x74, 0x3a, 0x70, 0x61, 0x72, 0x65, 0x6e, 0x74, 0x2d, 0x62, 0x6c, 0x6f, 0x63,
    0x6b, 0x2d, 0x68, 0x61, 0x73, 0x68, 0x2d, 0x73, 0x74, 0x61, 0x6e, 0x64, 0x2d, 0x69, 0x6e, 0x2d,
    0x2d, 0x2d, 0x2d, 0x2d, 0x2d,
];

const PI: [u8; 81] = [
    0x02, 0x65, 0xa9, 0x30, 0x37, 0x78, 0xfd, 0xb8, 0x30, 0x94, 0x77, 0xb7, 0x6c, 0x50, 0x55, 0xab,
    0x16, 0x9f, 0xec, 0x67, 0xc5, 0x39, 0xc5, 0x7e, 0x0b, 0x08, 0xce, 0x3c, 0x1c, 0x03, 0x83, 0xa8,
    0x4a, 0x11, 0x32, 0xa9, 0xc3, 0x33, 0x31, 0x31, 0x2c, 0x3a, 0x56, 0x12, 0x61, 0x73, 0x57, 0xce,
    0xf5, 0xbf, 0x0a, 0x35, 0x6b, 0x9e, 0x21, 0x83, 0x06, 0x8e, 0x60, 0x61, 0x87, 0xec, 0x21, 0x4f,
    0x8b, 0x55, 0x48, 0x62, 0x26, 0x8b, 0x26, 0x15, 0x76, 0x08, 0x7b, 0x33, 0x74, 0xfa, 0x49, 0xbd,
    0x2d,
];

/// CKB-VM's exit syscall. `code` reaches the debugger as the program's result.
unsafe fn exit(code: i8) -> ! {
    asm!("li a7, 93", "ecall", in("a0") code as usize, options(noreturn));
}

#[no_mangle]
pub extern "C" fn _start() -> ! {
    // black_box on both sides keeps the optimiser from folding a known-good
    // proof into a constant and reporting a cost of nothing.
    let code = match verify(black_box(&PUBKEY), black_box(&ALPHA), black_box(&PI)) {
        Ok(beta) => (black_box(beta)[0] & 0) as i8,
        Err(_) => 1,
    };
    unsafe { exit(code) }
}

#[panic_handler]
fn panic(_: &PanicInfo) -> ! {
    unsafe { exit(2) }
}
