//! Measures one ECVRF verification with ckb-std linked in.
//!
//! This is a benchmark, not a contract. Its counterpart `ckb/bench` measures
//! the cryptography alone; the difference between the two is what ckb-std's
//! entry and allocator cost, which every real script pays on top.

#![no_std]
#![cfg_attr(not(test), no_main)]

#[cfg(test)]
extern crate alloc;

#[cfg(not(test))]
use ckb_std::default_alloc;
#[cfg(not(test))]
ckb_std::entry!(program_entry);
#[cfg(not(test))]
default_alloc!();

use ckb_vrf::verify;

/// A proof produced by the L2 chain's prover. Fixed input keeps the figure
/// reproducible.
const PUBKEY: [u8; 33] = [
    0x02, 0x84, 0xbf, 0x75, 0x62, 0x26, 0x2b, 0xbd, 0x69, 0x40, 0x08, 0x57, 0x48, 0xf3, 0xbe, 0x6a,
    0xfa, 0x52, 0xae, 0x31, 0x71, 0x55, 0x18, 0x1e, 0xce, 0x31, 0xb6, 0x63, 0x51, 0xcc, 0xff, 0xa4,
    0xb0,
];

const ALPHA: [u8; 53] = [
    0x69, 0x6e, 0x76, 0x69, 0x73, 0x69, 0x62, 0x6f, 0x6f, 0x6b, 0x2d, 0x76, 0x72, 0x66, 0x2d, 0x69,
    0x6e, 0x70, 0x75, 0x74, 0x3a, 0x70, 0x61, 0x72, 0x65, 0x6e, 0x74, 0x2d, 0x62, 0x6c, 0x6f, 0x63,
    0x6b, 0x2d, 0x68, 0x61, 0x73, 0x68, 0x2d, 0x73, 0x74, 0x61, 0x6e, 0x64, 0x2d, 0x69, 0x6e, 0x2d,
    0x2d, 0x2d, 0x2d, 0x2d, 0x2d,
];

const PI: [u8; 81] = [
    0x02, 0x65, 0xa9, 0x30, 0x37, 0x78, 0xfd, 0xb8, 0x30, 0x94, 0x77, 0xb7, 0x6c, 0x50, 0x55, 0xab,
    0x16, 0x9f, 0xec, 0x67, 0xc5, 0x39, 0xc5, 0x7e, 0x0b, 0x08, 0xce, 0x3c, 0x1c, 0x03, 0x83, 0xa8,
    0x4a, 0x11, 0x32, 0xa9, 0xc3, 0x33, 0x31, 0x31, 0x2c, 0x3a, 0x56, 0x12, 0x61, 0x73, 0x57, 0xce,
    0xf5, 0xbf, 0x0a, 0x35, 0x6b, 0x9e, 0x21, 0x83, 0x06, 0x8e, 0x60, 0x61, 0x87, 0xec, 0x21, 0x4f,
    0x8b, 0x55, 0x48, 0x62, 0x26, 0x8b, 0x26, 0x15, 0x76, 0x08, 0x7b, 0x33, 0x74, 0xfa, 0x49, 0xbd,
    0x2d,
];

/// Verifies once and reports the outcome; the cycle count is the point.
pub fn program_entry() -> i8 {
    match verify(&PUBKEY, &ALPHA, &PI) {
        Ok(_) => 0,
        Err(_) => 1,
    }
}
